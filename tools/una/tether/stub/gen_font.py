"""Make font8x8.h from LVGL's lv_font_unscii_8.c: the 8 x 8 unscii-8 glyphs of
ASCII 0x20 to 0x7f, a byte a row, the most significant bit on the left.

    gen_font.py third_party/lvgl/lvgl/src/font/lv_font_unscii_8.c > font8x8.h
"""

import re
import sys


def main():
    src = open(sys.argv[1]).read()
    bitmap_src = re.search(r"glyph_bitmap\[\] = \{(.*?)\};", src, re.S).group(1)
    bitmap_src = re.sub(r"/\*.*?\*/", "", bitmap_src, flags=re.S)
    bitmap = [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]+", bitmap_src)]
    dsc = re.findall(
        r"\.bitmap_index = (\d+), \.adv_w = \d+, \.box_w = (\d+), \.box_h = (\d+), "
        r"\.ofs_x = (-?\d+), \.ofs_y = (-?\d+)",
        src,
    )
    # Glyph 0 is reserved; 1 is U+0020
    glyphs = dsc[1:97]
    assert len(glyphs) == 96, len(glyphs)

    rows_out = []
    for index, box_w, box_h, ofs_x, ofs_y in glyphs:
        index, box_w, box_h, ofs_x, ofs_y = map(int, (index, box_w, box_h, ofs_x, ofs_y))
        rows = [0] * 8
        bit = 0
        top = 8 - ofs_y - box_h
        for y in range(box_h):
            for x in range(box_w):
                byte = bitmap[index + bit // 8]
                if byte & (0x80 >> (bit % 8)):
                    row, col = top + y, ofs_x + x
                    if 0 <= row < 8 and 0 <= col < 8:
                        rows[row] |= 0x80 >> col
                bit += 1
        rows_out.append(rows)

    print("/* Generated by gen_font.py from LVGL's lv_font_unscii_8.c (MIT): the glyphs of */")
    print("/* unscii-8 by Viznut, which is in the public domain. ASCII 0x20 to 0x7f. */")
    print()
    print("#pragma once")
    print()
    print("#include <stdint.h>")
    print()
    print("static const uint8_t s_font8x8[96][8] = {")
    for code, rows in enumerate(rows_out, 0x20):
        ch = chr(code) if 0x20 <= code < 0x7F and chr(code) not in "\\*/" else " "
        print("  {" + ", ".join(f"0x{r:02x}" for r in rows) + f"}}, /* {code:#04x} {ch} */")
    print("};")


if __name__ == "__main__":
    main()

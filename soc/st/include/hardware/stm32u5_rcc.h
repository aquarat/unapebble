/* Register bit definitions */

#define RCC_CR_MSISON   PBL_BIT(0)
#define RCC_CR_MSISRDY  PBL_BIT(2)
#define RCC_CR_MSIKON   PBL_BIT(4)
#define RCC_CR_MSIKRDY  PBL_BIT(5)
#define RCC_CR_HSION    PBL_BIT(8)
#define RCC_CR_HSIRDY   PBL_BIT(10)
#define RCC_CR_HSI48ON  PBL_BIT(12)
#define RCC_CR_HSI48RDY PBL_BIT(13)
#define RCC_CR_HSEON    PBL_BIT(16)
#define RCC_CR_HSERDY   PBL_BIT(17)
#define RCC_CR_HSEBYP   PBL_BIT(18)
#define RCC_CR_PLL1ON   PBL_BIT(24)
#define RCC_CR_PLL1RDY  PBL_BIT(25)

/* MSIS and MSIK take their range from ICSCR1 once MSIRGSEL is set, from CSR otherwise */
#define RCC_ICSCR1_MSIRGSEL       PBL_BIT(23)
#define RCC_ICSCR1_MSIKRANGE_MASK PBL_GENMASK(27, 24)
#define RCC_ICSCR1_MSISRANGE_MASK PBL_GENMASK(31, 28)
#define RCC_CSR_MSIKSRANGE_MASK   PBL_GENMASK(11, 8)
#define RCC_CSR_MSISSRANGE_MASK   PBL_GENMASK(15, 12)

#define RCC_CFGR1_SW_MASK  PBL_GENMASK(1, 0)
#define RCC_CFGR1_SWS_MASK PBL_GENMASK(3, 2)
#define RCC_CFGR1_SW_MSIS  0U
#define RCC_CFGR1_SW_HSI16 1U
#define RCC_CFGR1_SW_HSE   2U
#define RCC_CFGR1_SW_PLL1  3U

/* HPRE: 0xxx divides by 1, 1000 to 1111 by 2 to 512 (no 32); PPRE: 0xx by 1, 100 to 111 by 2 to 16
 */
#define RCC_CFGR2_HPRE_MASK  PBL_GENMASK(3, 0)
#define RCC_CFGR2_PPRE1_MASK PBL_GENMASK(6, 4)
#define RCC_CFGR2_PPRE2_MASK PBL_GENMASK(10, 8)
#define RCC_CFGR3_PPRE3_MASK PBL_GENMASK(6, 4)
#define RCC_AHB_PRE_DIVIDED  0x8U
#define RCC_APB_PRE_DIVIDED  0x4U

#define RCC_PLL1CFGR_SRC_MASK    PBL_GENMASK(1, 0)
#define RCC_PLL1CFGR_SRC_NONE    0U
#define RCC_PLL1CFGR_SRC_MSIS    1U
#define RCC_PLL1CFGR_SRC_HSI16   2U
#define RCC_PLL1CFGR_SRC_HSE     3U
#define RCC_PLL1CFGR_RGE_MASK    PBL_GENMASK(3, 2)
#define RCC_PLL1CFGR_RGE_4_8MHZ  0U
#define RCC_PLL1CFGR_RGE_8_16MHZ 3U
#define RCC_PLL1CFGR_FRACEN      PBL_BIT(4)
#define RCC_PLL1CFGR_M_MASK      PBL_GENMASK(11, 8)
#define RCC_PLL1CFGR_MBOOST_MASK PBL_GENMASK(15, 12)
#define RCC_PLL1CFGR_PEN         PBL_BIT(16)
#define RCC_PLL1CFGR_QEN         PBL_BIT(17)
#define RCC_PLL1CFGR_REN         PBL_BIT(18)

#define RCC_PLL1DIVR_N_MASK PBL_GENMASK(8, 0)
#define RCC_PLL1DIVR_P_MASK PBL_GENMASK(15, 9)
#define RCC_PLL1DIVR_Q_MASK PBL_GENMASK(22, 16)
#define RCC_PLL1DIVR_R_MASK PBL_GENMASK(30, 24)

#define RCC_AHB3ENR_PWREN PBL_BIT(2)

#define RCC_APB3ENR_RTCAPBEN PBL_BIT(21)

/* Kernel clock selections */
#define RCC_CCIPR1_USART1SEL_MASK  PBL_GENMASK(1, 0)
#define RCC_CCIPR1_USART2SEL_MASK  PBL_GENMASK(3, 2)
#define RCC_CCIPR1_USART3SEL_MASK  PBL_GENMASK(5, 4)
#define RCC_CCIPR1_I2C1SEL_MASK    PBL_GENMASK(11, 10)
#define RCC_CCIPR1_I2C2SEL_MASK    PBL_GENMASK(13, 12)
#define RCC_CCIPR1_I2C4SEL_MASK    PBL_GENMASK(15, 14)
#define RCC_CCIPR1_SPI2SEL_MASK    PBL_GENMASK(17, 16)
#define RCC_CCIPR1_LPTIM2SEL_MASK  PBL_GENMASK(19, 18)
#define RCC_CCIPR1_SPI1SEL_MASK    PBL_GENMASK(21, 20)
#define RCC_CCIPR1_ICLKSEL_MASK    PBL_GENMASK(27, 26)
#define RCC_CCIPR2_RNGSEL_MASK     PBL_GENMASK(13, 12)
#define RCC_CCIPR2_SDMMCSEL        PBL_BIT(14)
#define RCC_CCIPR3_LPUART1SEL_MASK PBL_GENMASK(2, 0)
#define RCC_CCIPR3_SPI3SEL_MASK    PBL_GENMASK(4, 3)
#define RCC_CCIPR3_I2C3SEL_MASK    PBL_GENMASK(7, 6)
#define RCC_CCIPR3_LPTIM34SEL_MASK PBL_GENMASK(9, 8)
#define RCC_CCIPR3_LPTIM1SEL_MASK  PBL_GENMASK(11, 10)

/* USART: PCLK, SYSCLK, HSI16, LSE. LPUART1: PCLK3, SYSCLK, HSI16, LSE, MSIK. */
#define RCC_USARTSEL_PCLK   0U
#define RCC_USARTSEL_SYSCLK 1U
#define RCC_USARTSEL_HSI16  2U
#define RCC_USARTSEL_LSE    3U
#define RCC_USARTSEL_MSIK   4U
/* I2C and SPI: PCLK, SYSCLK, HSI16, MSIK */
#define RCC_I2CSEL_PCLK   0U
#define RCC_I2CSEL_SYSCLK 1U
#define RCC_I2CSEL_HSI16  2U
#define RCC_I2CSEL_MSIK   3U
/* LPTIM1, LPTIM3 and LPTIM4: MSIK, LSI, HSI16, LSE; LPTIM2 takes PCLK1 for MSIK */
#define RCC_LPTIMSEL_MSIK  0U
#define RCC_LPTIMSEL_LSI   1U
#define RCC_LPTIMSEL_HSI16 2U
#define RCC_LPTIMSEL_LSE   3U
/* RNG: HSI48, HSI48 / 2, HSI16 */
#define RCC_RNGSEL_HSI48 0U
#define RCC_RNGSEL_HSI16 2U
/* ICLK (CLK48): HSI48, PLL2 Q, PLL1 Q, MSIK */
#define RCC_ICLKSEL_HSI48  0U
#define RCC_ICLKSEL_PLL1_Q 2U
#define RCC_ICLKSEL_MSIK   3U

#define RCC_BDCR_LSEON       PBL_BIT(0)
#define RCC_BDCR_LSERDY      PBL_BIT(1)
#define RCC_BDCR_LSEBYP      PBL_BIT(2)
#define RCC_BDCR_LSEDRV_MASK PBL_GENMASK(4, 3)
#define RCC_BDCR_LSESYSEN    PBL_BIT(7)
#define RCC_BDCR_RTCSEL_MASK PBL_GENMASK(9, 8)
#define RCC_BDCR_RTCSEL_NONE 0U
#define RCC_BDCR_RTCSEL_LSE  1U
#define RCC_BDCR_RTCSEL_LSI  2U
#define RCC_BDCR_LSESYSRDY   PBL_BIT(11)
#define RCC_BDCR_RTCEN       PBL_BIT(15)
#define RCC_BDCR_LSION       PBL_BIT(26)
#define RCC_BDCR_LSIRDY      PBL_BIT(27)
#define RCC_BDCR_LSIPREDIV   PBL_BIT(28)

/* Reset flags, cleared with RMVF */
#define RCC_CSR_RMVF     PBL_BIT(23)
#define RCC_CSR_OBLRSTF  PBL_BIT(25)
#define RCC_CSR_PINRSTF  PBL_BIT(26)
#define RCC_CSR_BORRSTF  PBL_BIT(27)
#define RCC_CSR_SFTRSTF  PBL_BIT(28)
#define RCC_CSR_IWDGRSTF PBL_BIT(29)
#define RCC_CSR_WWDGRSTF PBL_BIT(30)
#define RCC_CSR_LPWRRSTF PBL_BIT(31)


#define STM32U5_RCC_CFGR3_OFFSET    0x0024
#define STM32U5_RCC_PLL1CFGR_OFFSET 0x0028
#define STM32U5_RCC_PLL1DIVR_OFFSET 0x0034
#define STM32U5_RCC_CIER_OFFSET     0x0050

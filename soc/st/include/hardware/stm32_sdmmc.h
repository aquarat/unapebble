#pragma once

#include <pbl/util/bits.h>

/* Register offsets of the SDMMC host with internal DMA, as on the STM32U5 and STM32H7 */

#define STM32_SDMMC_POWER_OFFSET     0x0000
#define STM32_SDMMC_CLKCR_OFFSET     0x0004
#define STM32_SDMMC_ARG_OFFSET       0x0008
#define STM32_SDMMC_CMD_OFFSET       0x000c
#define STM32_SDMMC_RESPCMD_OFFSET   0x0010
#define STM32_SDMMC_RESP1_OFFSET     0x0014
#define STM32_SDMMC_RESP2_OFFSET     0x0018
#define STM32_SDMMC_RESP3_OFFSET     0x001c
#define STM32_SDMMC_RESP4_OFFSET     0x0020
#define STM32_SDMMC_DTIMER_OFFSET    0x0024
#define STM32_SDMMC_DLEN_OFFSET      0x0028
#define STM32_SDMMC_DCTRL_OFFSET     0x002c
#define STM32_SDMMC_DCOUNT_OFFSET    0x0030
#define STM32_SDMMC_STA_OFFSET       0x0034
#define STM32_SDMMC_ICR_OFFSET       0x0038
#define STM32_SDMMC_MASK_OFFSET      0x003c
#define STM32_SDMMC_IDMACTRL_OFFSET  0x0050
#define STM32_SDMMC_IDMABSIZE_OFFSET 0x0054
#define STM32_SDMMC_IDMABASER_OFFSET 0x0058

/* Register bit definitions */

#define SDMMC_POWER_PWRCTRL_MASK  PBL_GENMASK(1, 0)
#define SDMMC_POWER_PWRCTRL_OFF   0U
#define SDMMC_POWER_PWRCTRL_CYCLE 2U
#define SDMMC_POWER_PWRCTRL_ON    3U

#define SDMMC_CLKCR_CLKDIV_MASK PBL_GENMASK(9, 0)
#define SDMMC_CLKCR_PWRSAV      PBL_BIT(12)
#define SDMMC_CLKCR_WIDBUS_MASK PBL_GENMASK(15, 14)
#define SDMMC_CLKCR_WIDBUS_1    0U
#define SDMMC_CLKCR_WIDBUS_4    1U
#define SDMMC_CLKCR_NEGEDGE     PBL_BIT(16)
#define SDMMC_CLKCR_HWFC_EN     PBL_BIT(17)
#define SDMMC_CLKCR_DDR         PBL_BIT(18)
#define SDMMC_CLKCR_BUSSPEED    PBL_BIT(19)

#define SDMMC_CMD_CMDINDEX_MASK   PBL_GENMASK(5, 0)
#define SDMMC_CMD_CMDTRANS        PBL_BIT(6)
#define SDMMC_CMD_CMDSTOP         PBL_BIT(7)
#define SDMMC_CMD_WAITRESP_MASK   PBL_GENMASK(9, 8)
#define SDMMC_CMD_WAITRESP_NONE   0U
#define SDMMC_CMD_WAITRESP_SHORT  1U
#define SDMMC_CMD_WAITRESP_NO_CRC 2U
#define SDMMC_CMD_WAITRESP_LONG   3U
#define SDMMC_CMD_CPSMEN          PBL_BIT(12)

#define SDMMC_DCTRL_DTEN            PBL_BIT(0)
#define SDMMC_DCTRL_DTDIR           PBL_BIT(1)
#define SDMMC_DCTRL_DTMODE_MASK     PBL_GENMASK(3, 2)
#define SDMMC_DCTRL_DBLOCKSIZE_MASK PBL_GENMASK(7, 4)
#define SDMMC_DCTRL_FIFORST         PBL_BIT(13)

#define SDMMC_STA_CCRCFAIL  PBL_BIT(0)
#define SDMMC_STA_DCRCFAIL  PBL_BIT(1)
#define SDMMC_STA_CTIMEOUT  PBL_BIT(2)
#define SDMMC_STA_DTIMEOUT  PBL_BIT(3)
#define SDMMC_STA_TXUNDERR  PBL_BIT(4)
#define SDMMC_STA_RXOVERR   PBL_BIT(5)
#define SDMMC_STA_CMDREND   PBL_BIT(6)
#define SDMMC_STA_CMDSENT   PBL_BIT(7)
#define SDMMC_STA_DATAEND   PBL_BIT(8)
#define SDMMC_STA_DABORT    PBL_BIT(11)
#define SDMMC_STA_DPSMACT   PBL_BIT(12)
#define SDMMC_STA_CPSMACT   PBL_BIT(13)
#define SDMMC_STA_BUSYD0    PBL_BIT(20)
#define SDMMC_STA_BUSYD0END PBL_BIT(21)
#define SDMMC_STA_IDMATE    PBL_BIT(27)
#define SDMMC_STA_IDMABTC   PBL_BIT(28)

/* The static flags, which ICR clears */
#define SDMMC_STA_STATIC_FLAGS (PBL_GENMASK(11, 0) | PBL_GENMASK(28, 21))

#define SDMMC_IDMACTRL_IDMAEN PBL_BIT(0)
